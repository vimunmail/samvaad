package com.example.xgestalkble.ui.conversation

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Simple statistics for an "analyze the chat" view.
 */
data class ConversationStats(
    val total: Int,
    val signCount: Int,
    val speechCount: Int,
    val durationMs: Long,
    val distinctSigns: Int,
    val topSigns: List<Pair<String, Int>>
)

/**
 * Turns a [SavedConversation] (or a live message list) into a shareable plain-text
 * or PDF transcript and hands it to the Android share sheet (WhatsApp, Gmail,
 * Drive, …). Also computes light analytics for the in-app "Analyze" view.
 *
 * Everything is offline; files are written to `cacheDir/exports` and shared via
 * the app's FileProvider.
 */
object ConversationExporter {

    private val stamp = SimpleDateFormat("EEE, d MMM yyyy · h:mm a", Locale.getDefault())
    private val timeOnly = SimpleDateFormat("h:mm a", Locale.getDefault())
    private val fileStamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US)

    /** Speaker prefix used in transcripts. Wearer's signs vs. the other person's speech. */
    private fun speaker(m: ChatMessage) = when {
        m.source == "guest" -> "Guest"
        m.source == "sign" -> "Glove (me)"
        m.fromGlove -> "Me"
        else -> "Speaker"
    }

    private fun line(m: ChatMessage): String {
        val t = timeOnly.format(Date(m.timestamp))
        val body = if (m.translation != null && m.translation != m.text)
            "${m.text}  (${m.translation})" else m.text
        return "[$t] ${speaker(m)}: $body"
    }

    /** Human-readable transcript with a header. */
    fun buildTranscript(conv: SavedConversation): String {
        val sb = StringBuilder()
        sb.appendLine("Samvaad — Conversation Transcript")
        sb.appendLine(conv.title)
        sb.appendLine(stamp.format(Date(conv.startedAt)))
        sb.appendLine("Messages: ${conv.messages.size}  ·  Signed: ${conv.signCount}  ·  Spoken: ${conv.speechCount}")
        sb.appendLine("────────────────────────────────────────")
        if (conv.messages.isEmpty()) sb.appendLine("(no messages)")
        conv.messages.forEach { sb.appendLine(line(it)) }
        sb.appendLine("────────────────────────────────────────")
        sb.appendLine("Generated by Samvaad")
        return sb.toString()
    }

    fun analyze(conv: SavedConversation): ConversationStats {
        val signs = conv.messages.filter { it.source == "sign" }.map { it.text.trim().uppercase(Locale.US) }
        val freq = signs.groupingBy { it }.eachCount()
        return ConversationStats(
            total = conv.messages.size,
            signCount = conv.signCount,
            speechCount = conv.speechCount,
            durationMs = (conv.endedAt - conv.startedAt).coerceAtLeast(0),
            distinctSigns = freq.size,
            topSigns = freq.entries.sortedByDescending { it.value }.take(5).map { it.key to it.value }
        )
    }

    // ── Sharing ──

    /** Quick share of the transcript as plain text — lands straight in WhatsApp etc. */
    fun shareText(context: Context, conv: SavedConversation) {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "Conversation: ${conv.title}")
            putExtra(Intent.EXTRA_TEXT, buildTranscript(conv))
        }
        launchChooser(context, intent, "Share conversation")
    }

    /** Export a .txt file and share it as an attachment. */
    fun shareTextFile(context: Context, conv: SavedConversation) {
        val file = File(exportsDir(context), "conversation_${fileStamp.format(Date(conv.startedAt))}.txt")
        file.writeText(buildTranscript(conv))
        shareFile(context, file, "text/plain", conv.title)
    }

    /** Render the transcript to a paginated A4 PDF and share it. */
    fun sharePdf(context: Context, conv: SavedConversation) {
        val file = File(exportsDir(context), "conversation_${fileStamp.format(Date(conv.startedAt))}.pdf")
        writePdf(conv, file)
        shareFile(context, file, "application/pdf", conv.title)
    }

    private fun shareFile(context: Context, file: File, mime: String, title: String) {
        val uri: Uri = FileProvider.getUriForFile(
            context, "${context.packageName}.fileprovider", file
        )
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = mime
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "Conversation: $title")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        launchChooser(context, intent, "Export conversation")
    }

    private fun launchChooser(context: Context, intent: Intent, title: String) {
        val chooser = Intent.createChooser(intent, title)
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        context.startActivity(chooser)
    }

    private fun exportsDir(context: Context): File =
        File(context.cacheDir, "exports").apply { mkdirs() }

    // ── PDF rendering ──

    private fun writePdf(conv: SavedConversation, out: File) {
        val pageW = 595   // A4 @ 72dpi
        val pageH = 842
        val margin = 40f
        val lineH = 18f
        val contentW = pageW - margin * 2

        val doc = PdfDocument()
        val title = Paint().apply { color = Color.BLACK; textSize = 16f; isFakeBoldText = true }
        val meta = Paint().apply { color = Color.DKGRAY; textSize = 10f }
        val me = Paint().apply { color = Color.rgb(0xC0, 0x2A, 0x2A); textSize = 11f; typeface = Typeface.DEFAULT_BOLD }
        val them = Paint().apply { color = Color.rgb(0x1A, 0x1A, 0x1A); textSize = 11f }

        var pageNo = 1
        var page = doc.startPage(PdfDocument.PageInfo.Builder(pageW, pageH, pageNo).create())
        var canvas = page.canvas
        var y = margin

        fun newPage() {
            doc.finishPage(page)
            pageNo++
            page = doc.startPage(PdfDocument.PageInfo.Builder(pageW, pageH, pageNo).create())
            canvas = page.canvas
            y = margin
        }

        // Wrap a string to the content width for a given paint.
        fun wrap(text: String, paint: Paint): List<String> {
            val words = text.split(" ")
            val lines = mutableListOf<String>()
            var cur = StringBuilder()
            words.forEach { w ->
                val trial = if (cur.isEmpty()) w else "$cur $w"
                if (paint.measureText(trial) > contentW && cur.isNotEmpty()) {
                    lines.add(cur.toString()); cur = StringBuilder(w)
                } else cur = StringBuilder(trial)
            }
            if (cur.isNotEmpty()) lines.add(cur.toString())
            return lines.ifEmpty { listOf("") }
        }

        fun draw(text: String, paint: Paint, gap: Float = 0f) {
            wrap(text, paint).forEach { ln ->
                if (y + lineH > pageH - margin) newPage()
                canvas.drawText(ln, margin, y, paint)
                y += lineH
            }
            y += gap
        }

        draw("Samvaad — Conversation Transcript", title, 2f)
        draw(conv.title, meta)
        draw(stamp.format(Date(conv.startedAt)), meta)
        draw("Messages: ${conv.messages.size}  ·  Signed: ${conv.signCount}  ·  Spoken: ${conv.speechCount}", meta, 10f)

        conv.messages.forEach { m ->
            val t = timeOnly.format(Date(m.timestamp))
            val body = if (m.translation != null && m.translation != m.text)
                "${m.text}  (${m.translation})" else m.text
            draw("[$t] ${speaker(m)}: $body", if (m.fromGlove) me else them, 2f)
        }

        doc.finishPage(page)
        out.outputStream().use { doc.writeTo(it) }
        doc.close()
    }
}
